-- Инициализационный скрипт для PostgreSQL
-- Выполняется автоматически при первом запуске контейнера

-- ============================================================================
-- РАСШИРЕНИЯ
-- ============================================================================

-- Расширение для полнотекстового поиска (для поиска по статьям ТК РФ)
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- Расширение для работы с UUID
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ============================================================================
-- НАСТРОЙКИ
-- ============================================================================

-- Включаем русский язык для полнотекстового поиска
-- Это позволит корректно искать по русским словам
ALTER DATABASE legal_agent SET default_text_search_config = 'russian';

-- ============================================================================
-- СООБЩЕНИЯ
-- ============================================================================

\echo '✅ База данных legal_agent (основная) инициализирована'
\echo '✅ Расширение pg_trgm установлено (полнотекстовый поиск)'
\echo '✅ Расширение uuid-ossp установлено'
\echo '✅ Настроена русская локаль для поиска'
