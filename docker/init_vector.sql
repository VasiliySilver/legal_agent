-- Инициализационный скрипт для PostgreSQL с pgvector
-- База данных для хранения векторных эмбеддингов статей

-- ============================================================================
-- РАСШИРЕНИЯ
-- ============================================================================

-- Расширение для векторного поиска
CREATE EXTENSION IF NOT EXISTS vector;

-- Расширение для UUID (синхронизация ID со статьями из основной БД)
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ============================================================================
-- НАСТРОЙКИ
-- ============================================================================

-- Настройки для оптимизации векторного поиска
ALTER DATABASE legal_agent_vectors SET maintenance_work_mem = '512MB';

-- ============================================================================
-- СООБЩЕНИЯ
-- ============================================================================

